  global.TMC_I18N = TMC_I18N;
  global.tmcHasKey = function (lang, path) {
    const dict = TMC_I18N[lang] || TMC_I18N.zh;
    const parts = path.split(".");
    let node = dict;
    for (const part of parts) {
      node = node && node[part];
    }
    return typeof node === "string";
  };
  global.tmcTranslate = function (lang, path, vars) {
    const dict = TMC_I18N[lang] || TMC_I18N.zh;
    const parts = path.split(".");
    let node = dict;
    for (const part of parts) {
      node = node && node[part];
    }
    if (typeof node !== "string") return path;
    const params = vars || {};
    return node.replace(/\{(\w+)\}/g, function (_, key) {
      return Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : "";
    });
  };
